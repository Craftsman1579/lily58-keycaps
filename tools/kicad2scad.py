# Lily58 Pro PCB (KiCad 5) -> OpenSCAD layout data for the case and the cap renders.
# Usage: kicad2scad.py <Lily58_Pro.kicad_pcb> <out.scad>
# Source: github.com/kata0510/Lily58, Pro/PCB/Lily58_Pro.kicad_pcb (MIT, (c) 2018 Naoki Katahira).
#
# The PCB is reversible; the file shows the RIGHT half seen from the top (switch side), with the
# Pro Micro and the thumb cluster on the inner (left) side. The left half is mirror([1, 0, 0]).
# Output coordinates: mm, y up (KiCad y is flipped), origin = lower left corner of the PCB bbox.
# Rotations stay as in KiCad (counter-clockwise as seen from the top).
import math, re, sys

src, dst = sys.argv[1:3]
s = open(src).read()

# --- board outline (Edge.Cuts consists of straight segments only) ---
segs = [tuple(map(float, g)) for g in re.findall(
    r'\(gr_line \(start ([-\d.]+) ([-\d.]+)\) \(end ([-\d.]+) ([-\d.]+)\) \(layer Edge.Cuts\)', s)]
assert not re.search(r'\(gr_arc[^\n]*Edge\.Cuts', s), 'arcs in Edge.Cuts are not supported'
pts = []
def snap(x, y):                                   # merge end points closer than 0.02 mm
    for i, (a, b) in enumerate(pts):
        if math.hypot(a - x, b - y) < 0.02:
            return i
    pts.append((x, y))
    return len(pts) - 1
adj = {}
for x1, y1, x2, y2 in segs:
    a, b = snap(x1, y1), snap(x2, y2)
    if a != b:
        adj.setdefault(a, []).append(b)
        adj.setdefault(b, []).append(a)
assert all(len(v) == 2 for v in adj.values()), 'outline is not a single closed loop'
loop, prev, cur = [0], None, 0
while True:
    nxt = [q for q in adj[cur] if q != prev][0]
    if nxt == 0:
        break
    loop.append(nxt)
    prev, cur = cur, nxt
assert len(loop) == len(adj), 'outline has more than one loop'
X0 = min(p[0] for p in pts)
Y1 = max(p[1] for p in pts)
def tx(x, y):
    return (x - X0, Y1 - y)
outline = [tx(*pts[i]) for i in loop]
area = sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(outline, outline[1:] + outline[:1]))
if area < 0:
    outline.reverse()                             # counter-clockwise

# --- footprints ---
mods = {}
for b in re.split(r'\n  \(module ', s)[1:]:
    ref = re.search(r'fp_text reference (\S+)', b).group(1)
    at = re.search(r'\(at ([-\d.]+) ([-\d.]+)(?: ([-\d.]+))?\)', b)
    drill = re.search(r'\(drill ([-\d.]+)\)', b)
    x, y = tx(float(at.group(1)), float(at.group(2)))
    mods[ref] = (b.split()[0].split(':')[1], x, y, float(at.group(3) or 0), float(drill.group(1)) if drill else 0)

# Switch numbering: SW1..SW6 number row, inner -> outer; SW19..SW24 bottom row;
# SW25 inner key next to the bottom row; SW26 1.5u thumb (rotated), SW27..SW29 thumbs inner -> outer.
def sw(n):
    return mods['SW%d' % n]
keys = []
for r in range(4):
    for c in range(6):
        _, x, y, rot, _ = sw(1 + 6 * r + c)
        keys.append((x, y, rot, r, c, 1.0))
for n, (r, c, w) in zip(range(25, 30), [(3, -1, 1.0), (4, -1, 1.5), (4, 0, 1.0), (4, 1, 1.0), (4, 2, 1.0)]):
    _, x, y, rot, _ = sw(n)
    keys.append((x, y, rot, r, c, w))

def f(v):
    return ('%.3f' % v).rstrip('0').rstrip('.')
def vec(*v):
    return '[' + ', '.join(f(a) for a in v) + ']'

with open(dst, 'w') as o:
    o.write('// Generated by tools/kicad2scad.py from kata0510/Lily58 Pro/PCB/Lily58_Pro.kicad_pcb\n')
    o.write('// (MIT, (c) 2018 Naoki Katahira). Do not edit by hand.\n')
    o.write('// RIGHT half seen from the switch side, mm, y up, origin = lower left of the PCB bbox.\n')
    o.write('// The left half is mirror([1, 0, 0]) of everything here.\n\n')
    o.write('lily58_pcb_thickness = 1.6;\n')
    o.write('lily58_pcb_size = %s;\n\n' % vec(max(p[0] for p in outline), max(p[1] for p in outline)))
    o.write('lily58_pcb_outline = [\n')
    for i in range(0, len(outline), 6):
        o.write('  ' + ', '.join(vec(*p) for p in outline[i:i + 6]) + ',\n')
    o.write('];\n\n')
    o.write('// [x, y, rotation, row, column, width in u]\n')
    o.write('// row 0 = number row … 3 = bottom row, 4 = thumbs; column 0 = innermost of the 6x4 block,\n')
    o.write('// -1 = inner key next to the bottom row / 1.5u thumb.\n')
    o.write('lily58_keys = [\n')
    for k in keys:
        o.write('  %s,\n' % vec(*k))
    o.write('];\n\n')
    o.write('// M2 mounting holes for the plate standoffs (the PCB holes are %s mm wide).\n' % f(mods['TH3'][4]))
    o.write('lily58_mount_holes = [%s];\n' % ', '.join(vec(mods['TH%d' % i][1], mods['TH%d' % i][2]) for i in range(3, 8)))
    o.write('lily58_mount_hole_d = %s;\n' % f(mods['TH3'][4]))
    o.write('// M2 holes for the OLED cover.\n')
    o.write('lily58_oled_holes = [%s];\n\n' % ', '.join(vec(mods['TH%d' % i][1], mods['TH%d' % i][2]) for i in (1, 2)))
    _, x, y, _, _ = mods['U1']
    o.write('// Pro Micro footprint origin (centre of the pin rows); USB faces +y (top PCB edge).\n')
    o.write('lily58_promicro = %s;\n' % vec(x, y))
    _, x, y, _, _ = mods['J2']
    o.write('// TRRS jack MJ-4PP-9 footprint origin; the plug opening faces +y.\n')
    o.write('lily58_trrs = %s;\n' % vec(x, y))
    _, x, y, _, _ = mods['RSW1']
    o.write('// Reset tact switch TVBP06.\n')
    o.write('lily58_reset = %s;\n' % vec(x, y))
    _, x, y, _, _ = mods['J3']
    o.write('// OLED 4-pin header, pin 1 (pins run +x).\n')
    o.write('lily58_oled_header = %s;\n\n' % vec(x, y))
    o.write('module lily58_pcb_2d() { polygon(lily58_pcb_outline); }\n')
print('outline points', len(outline), 'keys', len(keys), 'size', vec(max(p[0] for p in outline), max(p[1] for p in outline)))
